# 지도에는 적지만 검색·챗봇에서는 찾지 않는 이름
SKIP = {"방풍현관", "화단", "홀", "창고", "X", "ROOF", "OPEN", "주출입구", "▲ 주출입구", "연결통로", "로비/복도", "체육관 상부 OPEN", "옥외 데크"}
ICON = {"@m": "m", "@f": "f", "@e": "e", "@s": "s"}


def _cuts(spec):
    if "/" in spec:
        a, n = spec.split("/")
        x1, x2 = [float(v) for v in a.split(":")]
        return [x1 + (x2 - x1) * k / int(n) for k in range(int(n) + 1)]
    return [float(v) for v in spec.split(",")]


def _names(spec):
    out = []
    for p in spec.split(","):
        m = re.fullmatch(r"([A-Z])(\d+)\.\.[A-Z](\d+)", p)
        out += [m.group(1) + str(i) for i in range(int(m.group(2)), int(m.group(3)) + 1)] if m else [p]
    return out


def _em(text):
    return sum(1.0 if ord(ch) > 0x2E80 else (0.3 if ch == " " else 0.58) for ch in text)


def _split(text, n):
    # 글자를 n 줄로 고르게 나눔
    if n <= 1:
        return [text]
    cap, lines, cur = math.ceil(_em(text) / n - 0.01), [], ""
    for ch in text:
        if cur and len(lines) < n - 1 and _em(cur + ch) > cap + 0.01:
            lines.append(cur)
            cur = ""
        cur += ch
    lines.append(cur)
    return [x.strip() for x in lines if x.strip()]


def _fit(text, w, h):
    # 방 안에 들어가는 가장 큰 글자 크기와 줄바꿈. 이름에 ^ 를 넣어 두면 그 자리에서 줄을 바꿈 (예: 물리^R&E실)
    plain = text.replace("^", "")
    ok = lambda lines, fs: max(_em(x) for x in lines) * fs <= w - 3.5 and len(lines) * fs * 1.15 <= h - 1.5
    tries = [[plain]] + ([[x.strip() for x in text.split("^")]] if "^" in text else [])
    m = re.fullmatch(r"([A-Z])(\d{3})", plain)
    if m:
        tries.append([m.group(1), m.group(2)])
        w -= 4   # 기숙사 호실 번호는 옆 칸과 붙어 보이지 않게 조금 작게
    fs = 14.0
    while fs >= 7:
        for lines in tries:
            if ok(lines, fs):
                return fs, lines
        fs -= 0.5
    fs = 14.0
    while fs >= 4.5:
        for n in range(2, 9):
            lines = _split(plain, n)
            if ok(lines, fs):
                return fs, lines
        fs -= 0.5
    return 4.5, _split(plain, max(1, int(math.ceil(_em(plain) * 4.5 / max(w - 2, 4)))))


def build():
    out = []
    for bld, name, note, text in FLOORS:
        shapes = []   # (종류, x1, y1, x2, y2, 이름)  원은 (O, cx, cy, r, 종류, 이름)
        for line in text.strip().split("\n"):
            p = line.split(None, 5)
            if p[0] in ("R", "K"):
                a, b = float(p[1]), float(p[2])
                cuts = _cuts(p[3])
                names = _names(line.split(None, 4)[4])
                for k, nm in enumerate(names):
                    kind = ICON.get(nm, "r")
                    nm = "" if nm in ICON else nm
                    if p[0] == "R":
                        shapes.append((kind, cuts[k], a, cuts[k + 1], b, nm))
                    else:
                        shapes.append((kind, a, cuts[k], b, cuts[k + 1], nm))
            elif p[0] == "O":
                shapes.append(("O", float(p[1]), float(p[2]), float(p[3]), p[4], p[5] if len(p) > 5 else ""))
            else:
                shapes.append((p[0], float(p[1]), float(p[2]), float(p[3]), float(p[4]), p[5] if len(p) > 5 else ""))
        for i0, i1 in ((1, 3), (2, 4)):   # 거의 같은 자리에 있는 선은 한 줄로 맞춰서 방·복도·계단이 틈 없이 붙게 함
            vals, snap, grp = sorted({s[i] for s in shapes if s[0] != "O" for i in (i0, i1)}), {}, []
            for v in vals + [None]:
                if grp and (v is None or v - grp[0] > 7):
                    for g in grp:
                        snap[g] = round(sum(grp) / len(grp))
                    grp = []
                if v is not None:
                    grp.append(v)
            shapes = [s if s[0] == "O" else s[:i0] + (snap[s[i0]],) + s[i0 + 1:i1] + (snap[s[i1]],) + s[i1 + 1:] for s in shapes]
        xs, ys = [], []
        for s in shapes:
            if s[0] == "O":
                xs += [s[1] - s[3], s[1] + s[3]]
                ys += [s[2] - s[3], s[2] + s[3]]
            else:
                xs += [s[1], s[3]]
                ys += [s[2], s[4]]
        x0, y0, pad = min(xs), min(ys), 10
        k = 1000.0 / (max(xs) - x0)
        r1 = lambda v: round(v, 1)
        f = {"b": bld, "n": name, "w": 1000 + pad * 2, "h": int((max(ys) - y0) * k) + pad * 2, "note": note, "c": [], "r": [], "o": [], "t": []}
        for s in shapes:
            if s[0] == "O":
                cx, cy, rr = (s[1] - x0) * k + pad, (s[2] - y0) * k + pad, s[3] * k
                f["o"].append([r1(cx), r1(cy), r1(rr), s[4]])
                if s[5]:
                    nm = s[5].replace("^", "")
                    fs, lines = _fit(s[5], rr * 1.5, rr * 1.2)
                    f["t"].append([r1(cx), r1(cy), fs, "|".join(lines), "" if nm in SKIP else nm])
                continue
            x, y, w, h = (s[1] - x0) * k + pad, (s[2] - y0) * k + pad, (s[3] - s[1]) * k, (s[4] - s[2]) * k
            if s[0] == "c":
                f["c"].append([r1(x), r1(y), r1(w), r1(h)])
            elif s[0] != "l":
                f["r"].append([r1(x), r1(y), r1(w), r1(h), s[0]])
            if s[5]:
                nm = s[5].replace("^", "")
                fs, lines = _fit(s[5], w, h)
                f["t"].append([r1(x + w / 2), r1(y + h / 2), fs, "|".join(lines), "" if nm in SKIP else nm])
        out.append(f)
    return out


